// After `next build` (static export to out/), write out/sw.js that precaches every file so the game works offline.
import fs from 'fs';
import path from 'path';
import crypto from 'crypto';

const OUT = 'out';
const files = [];
const walk = (d) => {
  for (const f of fs.readdirSync(d)) {
    const p = path.join(d, f);
    if (fs.statSync(p).isDirectory()) walk(p);
    else if (!p.endsWith('sw.js')) files.push('/' + path.relative(OUT, p).split(path.sep).join('/'));
  }
};
walk(OUT);
const urls = files.map((f) => (f.endsWith('/index.html') ? f.slice(0, -'index.html'.length) : f));
const version = crypto.createHash('sha1').update(urls.join('|') + Date.now()).digest('hex').slice(0, 10);
const sw = `// generated by scripts/gen-sw.mjs
const CACHE = 'fitrun-${version}';
const PRECACHE = ${JSON.stringify(urls)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET') return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request).then((res) => {
    if (res.ok && new URL(e.request.url).origin === location.origin) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(e.request, copy)); }
    return res;
  }).catch(() => caches.match('/'))));
});
`;
fs.writeFileSync(path.join(OUT, 'sw.js'), sw);
console.log(`sw.js: ${urls.length} files precached`);
